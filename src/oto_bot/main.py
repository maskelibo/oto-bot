@app.command()
def dashboard() -> None:
    """Show the strategy comparison dashboard."""
    from rich.table import Table
    from rich.console import Console

    memory = MemoryManager()
    recent = memory.get_recent_results(n=50)
    if not recent:
        print("[dim]No experiments found. Run some cycles first.[/dim]")
        return

    console = Console()
    table = Table(title="Experiment Dashboard", show_header=True, header_style="bold magenta")
    table.add_column("#", style="dim", width=4)
    table.add_column("Strategy", style="cyan", max_width=35)
    table.add_column("Market")
    table.add_column("Sharpe", justify="right")
    table.add_column("Sortino", justify="right")
    table.add_column("ROI", justify="right")
    table.add_column("WR", justify="right")
    table.add_column("Max DD", justify="right", style="red")
    table.add_column("Trades", justify="right")
    table.add_column("Status", justify="center")

    for i, row in enumerate(recent[:20], 1):
        d = row["data"]
        cat = row.get("category", "")
        status = "[green]PROMO[/green]" if cat == "promotion" else "[yellow]HOLD[/yellow]"
        table.add_row(
            str(i),
            str(d.get("hypothesis_title", ""))[:35],
            str(d.get("market", "")),
            f"{d.get('sharpe', 0):.2f}",
            f"{d.get('sortino', 0):.2f}",
            f"{d.get('roi', 0):.1%}",
            f"{d.get('win_rate', 0):.1%}",
            f"{d.get('max_drawdown', 0):.1%}",
            str(d.get("total_trades", 0)),
            status,
        )
    console.print(table)


