def _pick_strategy(name: str):
    normalized = name.lower()
    if normalized == "day":
        return DayTraderStrategy()
    if normalized == "swing":
        return SwingTraderStrategy()
    if normalized == "scalp":
        return ScalperStrategy()
    if normalized in ("scalp2", "scalp_v2"):
        from oto_bot.strategies.scalper_v2 import ScalperV2Strategy
        return ScalperV2Strategy()
    raise typer.BadParameter("strategy must be one of: day, swing, scalp, scalp2")


def _fetch_data(market: str, symbol: str, timeframe: str):
    """Try real data providers, fall back to synthetic."""
    try:
        from oto_bot.data.factory import DataProviderFactory
        provider = DataProviderFactory.get_provider(market)
        data = provider.fetch_ohlcv(symbol, timeframe, limit=500)
        if data is not None and len(data) >= 100:
            return data
    except Exception:
        pass
    from oto_bot.utils.data import make_synthetic_ohlc
    return make_synthetic_ohlc(500)


@app.command()
def bootstrap() -> None:
    """Initialize the lab: create directories, seed agents, setup database."""
    for folder in ["memories", "experiments", "artifacts", "logs"]:
        Path(folder).mkdir(parents=True, exist_ok=True)
    registry = AgentRegistry()
    created = registry.seed_defaults()
    MemoryManager()
    print(f"[green]Bootstrap complete.[/green] Seeded {len(created)} new agents.")
    print("[dim]Database initialized at artifacts/experiments.sqlite3[/dim]")


@app.command()
def cycle(
    market: str = "crypto",
    strategy: str = "day",
    symbol: str = "BTCUSDT",
    timeframe: str = "1h",
) -> None:
    """Run a single research cycle."""
    registry = AgentRegistry()
    registry.seed_defaults()
    memory = MemoryManager()
    ceo = CEOAgent(registry, memory_manager=memory)
    ledger = ExperimentLedger()
    risk_gate = RiskGate()
    engine = BacktestEngine()
    strategy_impl = _pick_strategy(strategy)

    ceo_profile = registry.find_by_name("Atlas CEO")
    hypothesis = Hypothesis(
        title=f"{strategy_impl.name}_{market}_{symbol}",
        thesis="Baseline automated hypothesis generated by CEO cycle.",
        market=market,
        strategy_family=strategy,
        timeframe=timeframe,
        invalidation="Risk-adjusted metrics fail promotion gates.",
        expected_edge="Trend or mean-reversion persistence.",
        author_agent_id=ceo_profile.agent_id if ceo_profile else "unknown",
    )
    memory.save_hypothesis(hypothesis)

    data = _fetch_data(market, symbol, timeframe)
    context = StrategyContext(market=market, strategy_family=strategy, symbol=symbol, timeframe=timeframe)
    result = engine.run(strategy_impl, data, context)

    risk_report = risk_gate.approve(result)
    result.promoted = result.promoted and risk_report.approved
    result.notes = f"{result.notes}; risk_gate={risk_report.summary}; composite_score={composite_score(result):.4f}"

    memory.save_result(result)
    decision = ceo.review_experiment(result)

    ledger.log({
        "hypothesis": hypothesis.title,
        "market": market,
        "strategy": strategy,
        "result": {k: v for k, v in result.__dict__.items() if k != "created_at"}
        | {"created_at": result.created_at.isoformat()},
        "decision": {k: v for k, v in decision.__dict__.items() if k != "created_at"}
        | {"created_at": decision.created_at.isoformat()},
    })
    print("[bold cyan]Cycle finished[/bold cyan]")
    print(json.dumps({
        "hypothesis": hypothesis.title,
        "roi": result.roi,
        "win_rate": result.win_rate,
        "profit_factor": result.profit_factor,
        "sharpe": result.sharpe,
        "sortino": result.sortino,
        "cagr": result.cagr,
        "max_drawdown": result.max_drawdown,
        "total_trades": result.total_trades,
        "regime": result.regime,
        "decision": decision.decision,
        "reasoning": decision.reasoning,
    }, indent=2))


@app.command()
def autonomous(
    markets: str = "crypto,forex",
    strategies: str = "day,swing,scalp",
    max_cycles: int = 50,
    pause: float = 1.0,
) -> None:
    """Run the autonomous 24/7 research loop."""
    from oto_bot.orchestrator import Orchestrator

    market_list = [m.strip() for m in markets.split(",")]
    strategy_list = [s.strip() for s in strategies.split(",")]

    orchestrator = Orchestrator(
        markets=market_list,
        strategies=strategy_list,
        cycle_pause_seconds=pause,
        max_cycles=max_cycles,
    )
    orchestrator.run_autonomous()


